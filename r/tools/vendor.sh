# Bundles the libmedio sources of this repository (../src) and a few test
# datasets (../testsuite/data) into the R package, so that the package and
# the source tarball built with 'R CMD build' are self-contained: CRAN and
# other R repositories have no libmedio installed.
#
# Run this before 'R CMD build r'. 'configure' runs it automatically when the
# package is installed directly from a git checkout (R CMD INSTALL r).
# The bundled files are not tracked in git (see r/.gitignore).
#
# usage: r/tools/vendor.sh [--clean]
#        --clean  only remove the bundled files
#

set -e

pkgdir=$(cd "$(dirname "$0")/.." && pwd)
topdir=$(cd "${pkgdir}/.." && pwd)

dst="${pkgdir}/src/libmedio"
extdata="${pkgdir}/inst/extdata"

rm -rf "${dst}" "${extdata}"
if [ "$1" = "--clean" ]; then
  exit 0
fi

if [ ! -f "${topdir}/src/CMedIO.h" ] || [ ! -f "${topdir}/CMakeLists.txt" ]; then
  echo "ERROR: libmedio sources not found in '${topdir}'." >&2
  echo "       The R package has to be part of a libmedio source tree (directory r/)." >&2
  exit 1
fi

# library name and version as used by the CMake build (written into the
# headers of created files, e.g. the ECAT7 study description)
version=$(sed -n 's/^[[:space:]]*set(PKG_VERSION[[:space:]][[:space:]]*\([0-9][0-9.]*\)).*/\1/p' "${topdir}/CMakeLists.txt" | head -n 1)
longname=$(sed -n 's/^[[:space:]]*set(PROJECT_LONGNAME[[:space:]][[:space:]]*"\([^"]*\)").*/\1/p' "${topdir}/CMakeLists.txt" | head -n 1)
if [ -z "${version}" ] || [ -z "${longname}" ]; then
  echo "ERROR: cannot determine PKG_VERSION/PROJECT_LONGNAME from ${topdir}/CMakeLists.txt" >&2
  exit 1
fi

# copy the library sources (without the CMake build files)
mkdir -p "${dst}"
cp -R "${topdir}/src/." "${dst}/"
find "${dst}" -name CMakeLists.txt -exec rm -f {} +

# generate config.h like the CMake build does
sed -e "s/@PROJECT_LONGNAME@/${longname}/g" \
    -e "s/@PROJECT_VERSION@/${version}/g" \
    "${dst}/include/config.h.in" > "${dst}/include/config.h"
rm -f "${dst}/include/config.h.in"

# make variables with the sources and include directories, relative to r/src.
# configure puts them into src/Makevars, so the build needs no 'find' and no
# GNU make extensions (also on Windows).
{
  echo "# generated by tools/vendor.sh: libmedio ${version}"
  printf 'LIBMEDIO_SOURCES ='
  (cd "${pkgdir}/src" && find libmedio -name '*.cpp' | LC_ALL=C sort | sed 's/^/ /' | tr -d '\n')
  echo
  printf 'LIBMEDIO_INCLUDES = -Ilibmedio/include/stubs'
  (cd "${pkgdir}/src" && find libmedio -name '*.h' | sed 's|/[^/]*$||' | LC_ALL=C sort -u | sed 's/^/ -I/' | tr -d '\n')
  echo
} > "${dst}/files.mk"

# test datasets for the examples and tests (data file + expected values
# generated by independent implementations, see testsuite/data/README.md)
mkdir -p "${extdata}"
for f in ecat/pet-static.v ecat/pet-dynamic.v; do
  cp "${topdir}/testsuite/data/${f}" "${topdir}/testsuite/data/${f}.json" "${extdata}/"
done

echo "bundled libmedio ${version} into ${dst}"
